from __future__ import annotations

import hashlib
import os
from pathlib import Path
import subprocess
import sys

import pytest


ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts" / "sync_spec.py"
SPEC = ROOT / "spec" / "blog-figure-style.yaml"
TOKENS = ROOT / "src" / "blog_figure_style" / "tokens.py"
CANONICAL_MARKDOWN = Path(
    os.environ.get(
        "BLOG_DESIGN_SPEC",
        Path.home() / "Documents/Obsidian/My Design/Blog Design/Blog Figure Design System.md",
    )
)


def run_sync(*arguments: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        [sys.executable, str(SCRIPT), *arguments],
        cwd=ROOT,
        text=True,
        capture_output=True,
        check=False,
    )


def test_check_reports_committed_spec_and_tokens_are_current() -> None:
    result = run_sync("--check")

    assert result.returncode == 0, result.stdout + result.stderr


def test_generated_tokens_record_the_committed_yaml_sha256() -> None:
    digest = hashlib.sha256(SPEC.read_bytes()).hexdigest()

    assert "generated by scripts/sync_spec.py — do not edit" in TOKENS.read_text(
        encoding="utf-8"
    )
    assert f"source YAML sha256: {digest}" in TOKENS.read_text(encoding="utf-8")


def test_check_detects_drift_without_writing(tmp_path: Path) -> None:
    markdown = tmp_path / "design.md"
    spec = tmp_path / "style.yaml"
    tokens = tmp_path / "tokens.py"
    markdown.write_text(
        "before\n```yaml\n# blog-figure-style.yaml\n"
        "styles:\n  editorial_minimal:\n    palette:\n      bg: \"#000000\"\n"
        "```\nafter\n",
        encoding="utf-8",
    )
    spec.write_text("unchanged spec\n", encoding="utf-8")
    tokens.write_text("unchanged tokens\n", encoding="utf-8")

    result = run_sync(
        "--check",
        "--source",
        str(markdown),
        "--spec",
        str(spec),
        "--tokens",
        str(tokens),
    )

    assert result.returncode == 1
    assert spec.read_text(encoding="utf-8") == "unchanged spec\n"
    assert tokens.read_text(encoding="utf-8") == "unchanged tokens\n"


def test_committed_spec_matches_canonical_markdown_when_available() -> None:
    if not CANONICAL_MARKDOWN.exists():
        pytest.skip(f"canonical Markdown is not available: {CANONICAL_MARKDOWN}")

    result = run_sync("--check")

    assert result.returncode == 0, result.stdout + result.stderr
