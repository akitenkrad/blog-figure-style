#!/usr/bin/env python3
"""Synchronize the committed YAML spec and generated Python color tokens."""
from __future__ import annotations

import argparse
import hashlib
import os
from pathlib import Path
import sys
from typing import Any

import yaml


REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = Path(
    os.environ.get(
        "BLOG_DESIGN_SPEC",
        Path.home() / "Documents/Obsidian/My Design/Blog Design/Blog Figure Design System.md",
    )
)
DEFAULT_SPEC = REPOSITORY_ROOT / "spec" / "blog-figure-style.yaml"
DEFAULT_TOKENS = REPOSITORY_ROOT / "src" / "blog_figure_style" / "tokens.py"
YAML_MARKER = "# blog-figure-style.yaml"


def extract_yaml(markdown: str) -> str:
    """Extract the uniquely marked YAML fence while preserving its contents."""
    lines = markdown.splitlines()
    matches: list[tuple[int, int]] = []

    for fence_index, line in enumerate(lines):
        if line.strip() != "```yaml":
            continue
        content_index = fence_index + 1
        if content_index >= len(lines) or lines[content_index] != YAML_MARKER:
            continue
        for closing_index in range(content_index + 1, len(lines)):
            if lines[closing_index].strip() == "```":
                matches.append((content_index, closing_index))
                break
        else:
            raise ValueError("the marked YAML block has no closing fence")

    if len(matches) != 1:
        raise ValueError(
            f"expected exactly one YAML block beginning with {YAML_MARKER!r}; "
            f"found {len(matches)}"
        )

    start, end = matches[0]
    return "\n".join(lines[start:end]) + "\n"


def load_editorial_palette(yaml_text: str) -> dict[str, str]:
    """Parse and validate the light editorial-minimal palette."""
    document: Any = yaml.safe_load(yaml_text)
    try:
        palette = document["styles"]["editorial_minimal"]["palette"]
    except (KeyError, TypeError) as error:
        raise ValueError("YAML has no styles.editorial_minimal.palette mapping") from error

    if not isinstance(palette, dict) or not palette:
        raise ValueError("editorial_minimal.palette must be a non-empty mapping")
    if not all(isinstance(key, str) and isinstance(value, str) for key, value in palette.items()):
        raise ValueError("editorial_minimal.palette keys and values must be strings")

    return dict(palette)


def render_tokens(yaml_text: str) -> str:
    """Render deterministic Python constants from the light palette."""
    palette = load_editorial_palette(yaml_text)
    digest = hashlib.sha256(yaml_text.encode("utf-8")).hexdigest()
    constants = "\n".join(f'{key.upper()} = "{value}"' for key, value in palette.items())
    mapping = "\n".join(f'    "{key}": {key.upper()},' for key in palette)
    exports = "\n".join(f'    "{key.upper()}",' for key in palette)

    return f'''# generated by scripts/sync_spec.py — do not edit
# source YAML sha256: {digest}
"""Generated color tokens for the editorial-minimal figure style."""
from __future__ import annotations

{constants}

EDITORIAL_MINIMAL: dict[str, str] = {{
{mapping}
}}

__all__ = [
{exports}
    "EDITORIAL_MINIMAL",
]
'''


def expected_contents(source: Path, spec: Path, *, check: bool) -> tuple[str, str, bool]:
    """Return expected spec/tokens and whether the canonical source was available."""
    if source.exists():
        yaml_text = extract_yaml(source.read_text(encoding="utf-8"))
        return yaml_text, render_tokens(yaml_text), True

    if check and spec.exists():
        yaml_text = spec.read_text(encoding="utf-8")
        return yaml_text, render_tokens(yaml_text), False

    raise FileNotFoundError(f"canonical Markdown is not available: {source}")


def check_file(path: Path, expected: str) -> bool:
    """Report whether a generated file exactly matches expected text."""
    return path.exists() and path.read_text(encoding="utf-8") == expected


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check without writing")
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--spec", type=Path, default=DEFAULT_SPEC)
    parser.add_argument("--tokens", type=Path, default=DEFAULT_TOKENS)
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    try:
        spec_text, tokens_text, source_available = expected_contents(
            args.source,
            args.spec,
            check=args.check,
        )
    except (FileNotFoundError, OSError, ValueError, yaml.YAMLError) as error:
        print(f"error: {error}", file=sys.stderr)
        return 2

    if args.check:
        if not source_available:
            print(
                f"canonical Markdown is not available; checking committed spec only: {args.source}",
                file=sys.stderr,
            )
        stale = [
            path
            for path, expected in ((args.spec, spec_text), (args.tokens, tokens_text))
            if not check_file(path, expected)
        ]
        if stale:
            for path in stale:
                print(f"out of date: {path}", file=sys.stderr)
            return 1
        print("spec and generated tokens are up to date")
        return 0

    for path, content in ((args.spec, spec_text), (args.tokens, tokens_text)):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
